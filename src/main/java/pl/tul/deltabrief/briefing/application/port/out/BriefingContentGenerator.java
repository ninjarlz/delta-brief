package pl.tul.deltabrief.briefing.application.port.out;

import com.fasterxml.jackson.annotation.JsonPropertyDescription;
import java.util.List;
import pl.tul.deltabrief.briefing.domain.BriefingType;
import pl.tul.deltabrief.briefing.domain.IngestedItem;

/**
 * Port for generating a briefing's six narrative sections via an LLM. The
 * anti-hallucination guardrail (AGENTS.md) is enforced by the adapter's
 * prompt design (see plan.md's "Anti-hallucination via numbered citation"),
 * not by this port's contract — this interface only carries the data needed
 * to build that prompt.
 */
public interface BriefingContentGenerator {

	GeneratedBriefingContent generate(GenerationRequest request);

	/**
	 * @param previousBriefing null for {@link BriefingType#ONBOARDING} —
	 * there is no prior briefing to compare against.
	 * @param ingestedItems the numbered source list the prompt cites by
	 * index; also becomes the rendered "sources" section of the briefing.
	 */
	record GenerationRequest(String topicName, String categoryName, BriefingType type,
			PreviousBriefing previousBriefing, List<IngestedItem> ingestedItems) {
	}

	record PreviousBriefing(String keyChanges, String trendContinuation, String noiseSpeculation,
			String significance, String uncertainties, String sourceImpact) {
	}

	/**
	 * The six narrative sections of a briefing (FR-010) — the exact type
	 * passed to Spring AI's {@code ChatClient.call().entity(...)}. Each
	 * field's {@code @JsonPropertyDescription} becomes part of the JSON
	 * schema embedded in the generation prompt, instructing the model
	 * precisely what belongs in that section. FR-010's seventh section,
	 * "sources", is NOT generated by the model — it's rendered directly from
	 * {@link GenerationRequest#ingestedItems()} (see plan.md's numbered-
	 * citation design).
	 */
	record GeneratedBriefingContent(
			@JsonPropertyDescription("What genuinely changed the situation since the baseline, citing sources by [n]. A brief note if nothing genuinely changed.")
			String keyChanges,

			@JsonPropertyDescription("Developments that continue an existing trend rather than mark a genuine change, citing sources by [n]. A brief note if not applicable.")
			String trendContinuation,

			@JsonPropertyDescription("Content that is noise, repetition, or unverified speculation rather than a substantive development, citing sources by [n] where relevant. Say 'No noise detected' if none.")
			String noiseSpeculation,

			@JsonPropertyDescription("Why the key changes matter — the stakes and implications for someone following this topic.")
			String significance,

			@JsonPropertyDescription("What remains uncertain or unresolved about the situation.")
			String uncertainties,

			@JsonPropertyDescription("How the changes affect the range of plausible future scenarios for this topic.")
			String sourceImpact) {
	}

	class GenerationFailedException extends RuntimeException {

		public GenerationFailedException(Throwable cause) {
			super("Briefing content generation failed", cause);
		}

	}

}
